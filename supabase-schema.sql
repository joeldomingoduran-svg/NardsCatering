-- Identifiers are quoted to preserve the original MySQL table and column casing.
-- This creates the schema only; existing MySQL rows must be migrated separately.

DO $$
BEGIN
  CREATE TYPE staff_role AS ENUM ('admin', 'manager', 'staff');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END;
$$;

ALTER TYPE staff_role ADD VALUE IF NOT EXISTS 'manager';

DO $$
BEGIN
  CREATE TYPE booking_status AS ENUM ('pending', 'confirmed', 'completed', 'cancelled');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END;
$$;

DO $$
BEGIN
  CREATE TYPE payment_status AS ENUM ('unpaid', 'paid', 'failed');
EXCEPTION
  WHEN duplicate_object THEN NULL;
END;

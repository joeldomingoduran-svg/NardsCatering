DO $$
DECLARE
  column_info record;
  default_value integer;
BEGIN
  FOR column_info IN
    SELECT table_name, column_name
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND data_type = 'boolean'
      AND (
        (table_name = 'StaffUsers' AND column_name = 'is_active')
        OR (table_name IN ('Inventory', 'Packages', 'CateringAssets', 'Dishes') AND column_name = 'is_archived')
      )
  LOOP
    default_value := CASE WHEN column_info.column_name = 'is_active' THEN 1 ELSE 0 END;
    EXECUTE format('ALTER TABLE %I ALTER COLUMN %I DROP DEFAULT', column_info.table_name, column_info.column_name);
    EXECUTE format(
      'ALTER TABLE %I ALTER COLUMN %I TYPE smallint USING CASE WHEN %I THEN 1 ELSE 0 END',
      column_info.table_name, column_info.column_name, column_info.column_name
    );
    EXECUTE format(
      'ALTER TABLE %I ALTER COLUMN %I SET DEFAULT %s',
      column_info.table_name, column_info.column_name, default_value
    );
  END LOOP;
END;
$$;

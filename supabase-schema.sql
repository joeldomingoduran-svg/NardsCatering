CREATE TABLE IF NOT EXISTS "DishIngredients" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "dish_id" integer NOT NULL,
  "inventory_id" integer NOT NULL,
  "qty_required" integer NOT NULL DEFAULT 1,
  CONSTRAINT uq_dish_inventory UNIQUE ("dish_id", "inventory_id"),
  CONSTRAINT fk_dish_ingredients_dish
    FOREIGN KEY ("dish_id") REFERENCES "Dishes" ("id") ON DELETE CASCADE,
  CONSTRAINT fk_dish_ingredients_inventory
    FOREIGN KEY ("inventory_id") REFERENCES "Inventory" ("id") ON DELETE CASCADE

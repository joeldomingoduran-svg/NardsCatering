CREATE TABLE IF NOT EXISTS "PackageAssets" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "package_id" integer NOT NULL,
  "asset_id" integer NOT NULL,
  "qty_required" integer NOT NULL DEFAULT 1,
  CONSTRAINT fk_package_assets_package
    FOREIGN KEY ("package_id") REFERENCES "Packages" ("id") ON DELETE CASCADE,
  CONSTRAINT fk_package_assets_asset
    FOREIGN KEY ("asset_id") REFERENCES "CateringAssets" ("id") ON DELETE CASCADE

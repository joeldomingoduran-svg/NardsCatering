CREATE TABLE IF NOT EXISTS "Clients" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(255) NOT NULL,
  "contact" varchar(20) NOT NULL DEFAULT '+63 000 000 0000',
  "email" varchar(255) NOT NULL,
  "password" varchar(255) NOT NULL DEFAULT '',
  "isVerified" smallint NOT NULL DEFAULT 0,
  "otpHash" varchar(64),
  "otpExpires" timestamp,
  "otpAttempts" integer NOT NULL DEFAULT 0,
  "otpSentAt" timestamp,
  "resetHash" varchar(64),
  "resetExpires" timestamp,
  "resetAttempts" integer NOT NULL DEFAULT 0,
  "otpSendCount" integer NOT NULL DEFAULT 0,
  "otpWindowStart" timestamp,
  "resetSendCount" integer NOT NULL DEFAULT 0,
  "resetWindowStart" timestamp,
  CONSTRAINT uq_clients_email UNIQUE ("email")
);

CREATE TABLE IF NOT EXISTS "StaffUsers" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(255) NOT NULL,
  "username" varchar(100) NOT NULL,
  "password" varchar(255) NOT NULL,
  "role" staff_role NOT NULL DEFAULT 'staff',
  "is_active" smallint NOT NULL DEFAULT 1,
  "created_at" timestamptz DEFAULT CURRENT_TIMESTAMP,
  "profileImage" varchar(255),
  CONSTRAINT uq_staff_users_username UNIQUE ("username")
);

CREATE TABLE IF NOT EXISTS "LoginHistory" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" integer NOT NULL,
  "username" varchar(100) NOT NULL,
  "role" staff_role NOT NULL,
  "logged_in_at" timestamptz DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_login_history_user
    FOREIGN KEY ("user_id") REFERENCES "StaffUsers" ("id") ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_login_history_user
  ON "LoginHistory" ("user_id");

CREATE TABLE IF NOT EXISTS "Bookings" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "clientName" varchar(255) NOT NULL,
  "address" varchar(500) NOT NULL DEFAULT '',
  "eventType" varchar(100) NOT NULL DEFAULT '',
  "package" varchar(50) NOT NULL DEFAULT '',
  "eventDate" date NOT NULL,
  "phone" varchar(20) NOT NULL DEFAULT '',
  "status" booking_status NOT NULL DEFAULT 'pending',
  "cancellationReason" varchar(500),
  "notes" text,
  "email" varchar(255),
  "guests" integer NOT NULL DEFAULT 0,
  "stripePaymentIntentId" varchar(255),
  "paymentStatus" payment_status NOT NULL DEFAULT 'unpaid',
  "downPaymentAmount" numeric(10, 2),
  "termsAcceptedAt" timestamp,
  "termsVersion" varchar(20),
  "paymentOption" varchar(10),
  "amountDue" numeric(10, 2),
  "gcashRef" varchar(50),
  "paymentProof" varchar(255),
  "paymentDeadline" timestamp,
  "eventTime" time,
  "requestType" varchar(12),
  "requestReason" varchar(1000),
  "requestNewDate" date,
  "requestAt" timestamp,
  "requestHandled" smallint NOT NULL DEFAULT 0,
  "requestNewTime" time,
  "requestDecision" varchar(10),
  "requestResponse" varchar(500),
  "is_archived" smallint NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS "Inventory" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(255) NOT NULL,
  "quantity" integer NOT NULL DEFAULT 0,
  "threshold" integer NOT NULL DEFAULT 0,
  "is_archived" smallint NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS "Menu" (
  "id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "name" varchar(255) NOT NULL,
  "description" text,
  "price" numeric(10, 2) NOT NULL
